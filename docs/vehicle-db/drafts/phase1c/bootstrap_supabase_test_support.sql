-- TEST SUPPORT ONLY. Run only inside the disposable `phase1c_acceptance` Docker DB.
-- This creates Supabase platform objects needed by the checked-in migrations;
-- Vehicle Master schema itself is replayed from repository SQL files.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $$ BEGIN
  CREATE ROLE anon NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE ROLE authenticated NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE ROLE service_role NOLOGIN BYPASSRLS;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE IF NOT EXISTS auth.users (id uuid PRIMARY KEY);
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

-- v15 references these legacy TDR relations but the Phase 1C tests never use
-- their data. Their minimum column/FK contract is established only for replay.
CREATE TABLE IF NOT EXISTS public.brands (id uuid PRIMARY KEY DEFAULT gen_random_uuid());
CREATE TABLE IF NOT EXISTS public.models (id uuid PRIMARY KEY DEFAULT gen_random_uuid());
CREATE TABLE IF NOT EXISTS public.registrations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_id text,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE public.registrations ENABLE ROW LEVEL SECURITY;

-- The Ice migrations depend on this standard trigger function from the prior
-- platform baseline. It is intentionally identical in effect to the baseline
-- helper, and does not define Vehicle Master behavior.
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END $$;

CREATE SCHEMA IF NOT EXISTS storage;
CREATE TABLE IF NOT EXISTS storage.buckets (
  id text PRIMARY KEY,
  name text NOT NULL,
  public boolean NOT NULL DEFAULT false,
  file_size_limit bigint,
  allowed_mime_types text[]
);

CREATE TABLE IF NOT EXISTS public.phase1c_local_guard (
  only_disposable_local boolean PRIMARY KEY CHECK (only_disposable_local),
  database_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.phase1c_local_guard(only_disposable_local, database_name)
VALUES (true, current_database());
